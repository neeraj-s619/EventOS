@router.post("/alignment/trigger")
async def trigger_alignment_sync(
    service: NugenEventIntelligenceService = Depends(get_nugen_service)
):
    """
    Triggers or verifies the domain alignment workflow with the Nugen platform.
    Verifies dataset integrity and model deployment state.
    """
    manager = service.alignment_manager
    result = await manager.trigger_or_verify_alignment(service.client)
    return result


